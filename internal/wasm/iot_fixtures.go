func generateWasmModule(simpleModule []byte) []byte {
	return simpleModule
}

func GetAllFixtures() []IoTFixture {
	return []IoTFixture{
		SensorWasm,
		ActuatorWasm,
		StateMachineWasm,
		MemoryStressWasm,
		ErrorWasm,
	}
}

func GetFixtureByType(fixtureType IoTFixtureType) *IoTFixture {
	switch fixtureType {
	case FixtureSensor:
		return &SensorWasm
	case FixtureActuator:
		return &ActuatorWasm
	case FixtureStateMachine:
		return &StateMachineWasm
	case FixtureMemoryStress:
		return &MemoryStressWasm
	case FixtureError:
		return &ErrorWasm
	default:
		return nil
	}
}

func GetFixtureByName(name string) *IoTFixture {
	for _, fixture := range GetAllFixtures() {
		if fixture.Name == name {
			return &fixture
		}
	}
	return nil
}

func ValidateFixture(fixture *IoTFixture) error {
	if fixture == nil {
		return fmt.Errorf("fixture is nil")
	}

	if len(fixture.Bytecode) < 8 {
		return fmt.Errorf("fixture bytecode too short")
	}

	if fixture.Bytecode[0] != 0x00 || fixture.Bytecode[1] != 0x61 || fixture.Bytecode[2] != 0x73 || fixture.Bytecode[3] != 0x6d {
		return fmt.Errorf("invalid WASM magic number")
	}

	return nil
}

func FixtureToHex(fixture *IoTFixture) string {
	return hex.EncodeToString(fixture.Bytecode)
}

func HexToFixture(hexStr string) (*IoTFixture, error) {
	data, err := hex.DecodeString(hexStr)
	if err != nil {
		return nil, fmt.Errorf("failed to decode hex: %w", err)
	}

	return &IoTFixture{
		Bytecode: data,
	}, nil
}

type IoTFixtureSuite struct {
	Name     string
	Fixtures []IoTFixture
}

func NewIoTFixtureSuite(name string) *IoTFixtureSuite {
	return &IoTFixtureSuite{
		Name:     name,
		Fixtures: GetAllFixtures(),
	}
}

func (s *IoTFixtureSuite) Validate() error {
	for _, fixture := range s.Fixtures {
		if err := ValidateFixture(&fixture); err != nil {
			return fmt.Errorf("fixture %s validation failed: %w", fixture.Name, err)
		}
	}
	return nil
}
